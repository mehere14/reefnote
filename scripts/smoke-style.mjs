 await page.getByRole('button',{name:'Apply style',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'hidden'});
 const book=(await api(`novels/${novel.id}/cards?section=styles`))[0];assert(book.body.includes('Concrete verbs'));
 console.log('Opening scene');await page.goto(`${base}/n/${novel.id}/chapters/${scene.id}`);
 await page.getByLabel('POV character').selectOption(character.id);
