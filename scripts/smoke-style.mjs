const {novel}=await api('novels','POST',{title:'Style browser verification'});
const {card:chapter}=await api(`novels/${novel.id}/cards`,'POST',{type:'chapter',title:'Departure'});
const {card:scene}=await api(`novels/${novel.id}/cards`,'POST',{type:'scene',title:'The airlock',parentId:chapter.id});
const {card:character}=await api(`novels/${novel.id}/cards`,'POST',{type:'character',title:'Mara',body:'A surveyor.\n## History\nKeep this biography.'});
const browser=await chromium.launch({headless:true,channel:'chrome'});
